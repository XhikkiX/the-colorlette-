// Лучше бы я в Майн играл...
// Photo → palette — взвешенный median-cut, всё целиком на клиенте (фото читается
// через FileReader и никуда не отправляется). три вещи делают его точнее
// наивного median-cut по пикселям:
//  1. пиксели сначала сжимаются в грубую гистограмму (каждый канал округляется
//     до шага 4) — тысячи почти одинаковых пикселей сглаживания на краях
//     становятся одним взвешенным бином, а не портят среднее по отдельности
//  2. почти-белые/почти-чёрные бины (UI-хром, подписи, рамки, фон фото)
//     выкидываются перед разбиением — кроме случаев, когда они составляют
//     большую часть картинки, тогда оставляем, чтобы реально бело/чёрно-доминантные
//     фото тоже нормально работали
//  3. каждое разбиение и каждый итоговый свотч взвешены по числу пикселей,
//     которые бин реально представляет — так цвет бакета это честное
//     взвешенное среднее/медиана по популяции, а не то, куда его утянуло
//     парой случайных цветов
function buildColorHistogram(pixels){
  const map=new Map();
  for(let i=0;i<pixels.length;i+=3){
    const r=(pixels[i]>>2)<<2,g=(pixels[i+1]>>2)<<2,b=(pixels[i+2]>>2)<<2;
    const key=(r<<16)|(g<<8)|b;
    const e=map.get(key);
    if(e) e.n++;
    else map.set(key,{r,g,b,n:1});
  }
  return Array.from(map.values());
}
function dropExtremeBins(bins,totalWeight){
  const near=(b,v,dir)=>dir==="w"?(b.r>=v&&b.g>=v&&b.b>=v):(b.r<=v&&b.g<=v&&b.b<=v);
  const kept=bins.filter(b=>!near(b,246,"w")&&!near(b,10,"b"));
  const keptWeight=kept.reduce((s,b)=>s+b.n,0);
  return keptWeight>totalWeight*0.12?kept:bins;
}
function extractPaletteFromPixels(pixels,count){
  if(!pixels.length) return [];
  let bins=buildColorHistogram(pixels);
  const totalWeight=bins.reduce((s,b)=>s+b.n,0);
  bins=dropExtremeBins(bins,totalWeight);
  if(!bins.length) return [];
  // разбиваем с запасом (примерно в 4 раза больше свотчей, чем нужно, минимум 16),
  // а не останавливаемся сразу на `count` бакетах. делить "бакет с самым широким
  // диапазоном в одном канале" звучит логично, но это известная слабость обычного
  // median-cut: он может продолжать дробить уже и так чёткий бакет, пока два
  // реально разных оттенка сидят слипшимися в другом, более крупном — просто
  // потому что у того бакета самый широкий канал численно меньше. делим по
  // *популяции* — всегда режем бакет, который сейчас представляет больше всего
  // пикселей, — это давит именно на те бакеты, которые нужно разделить, а уход
  // далеко за `count` перед финальным отбором позволяет остаткам анти-алиасинга
  // и текста осесть в своих маленьких, легко отбрасываемых бакетах, а не
  // вытеснить настоящий цвет или смешаться с ним
  const targetBuckets=Math.min(bins.length,Math.max(count*6,24));
  let buckets=[bins];
  while(buckets.length<targetBuckets){
    let idx=-1,maxWeight=-1;
    buckets.forEach((b,i)=>{
      if(b.length<2) return;
      const w=b.reduce((s,p)=>s+p.n,0);
      if(w>maxWeight){maxWeight=w;idx=i}
    });
    if(idx===-1) break;
    const bucket=buckets[idx];
    let rMin=255,rMax=0,gMin=255,gMax=0,bMin=255,bMax=0;
    for(const p of bucket){
      if(p.r<rMin)rMin=p.r;if(p.r>rMax)rMax=p.r;
      if(p.g<gMin)gMin=p.g;if(p.g>gMax)gMax=p.g;
      if(p.b<bMin)bMin=p.b;if(p.b>bMax)bMax=p.b;
    }
    const rRange=rMax-rMin,gRange=gMax-gMin,bRange=bMax-bMin;
    if(rRange===0&&gRange===0&&bRange===0) break;
    const ch=(rRange>=gRange&&rRange>=bRange)?"r":(gRange>=bRange?"g":"b");
    bucket.sort((a,b)=>a[ch]-b[ch]);
    let acc=0,splitIdx=0;
    for(let i=0;i<bucket.length;i++){
      acc+=bucket[i].n;
      if(acc>=maxWeight/2){splitIdx=i+1;break}
    }
    if(splitIdx<=0||splitIdx>=bucket.length) splitIdx=Math.max(1,Math.floor(bucket.length/2));
    buckets.splice(idx,1,bucket.slice(0,splitIdx),bucket.slice(splitIdx));
  }
  // если ранжировать кандидатов просто по числу пикселей, маленькие, но яркие
  // детали (ярко-красная шапка на фоне огромного тусклого леса) хоронятся под
  // любым тусклым тоном, который просто занимает больше площади — а раз
  // несколько таких больших областей это чуть разные оттенки одного и того же
  // цвета, топ по популяции часто возвращает три почти одинаковых бежевых
  // вместо одного бежевого плюс что-то реально выделяющееся.
  // два фикса разом:
  //  1. считаем и по популяции, и по насыщенности — маленькое яркое пятно
  //     может обойти большое, но плоское
  //  2. выбираем жадно, но пропускаем кандидата, если он слишком близко
  //     (в RGB) к уже выбранному — почти одинаковые оттенки не проходят
  //     скопом только потому, что каждый по отдельности популярен
  const sat=(r,g,b)=>{const mx=Math.max(r,g,b),mn=Math.min(r,g,b);return mx===0?0:(mx-mn)/mx};
  const dist=(a,b)=>{const dr=a.r-b.r,dg=a.g-b.g,db=a.bl-b.bl;return Math.sqrt(dr*dr+dg*dg+db*db)};
  const candidates=buckets.filter(b=>b.length).map(b=>{
    let r=0,g=0,bl=0,n=0;
    for(const p of b){r+=p.r*p.n;g+=p.g*p.n;bl+=p.b*p.n;n+=p.n}
    r/=n;g/=n;bl/=n;
    return {hex:hex([r,g,bl]),r,g,bl,n,score:n*(1+1.6*sat(r,g,bl))};
  }).sort((a,b)=>b.score-a.score);
  const MIN_DIST=42;
  const picked=[];
  for(const c of candidates){
    if(picked.length>=count) break;
    if(picked.every(p=>dist(p,c)>=MIN_DIST)) picked.push(c);
  }
  if(picked.length<count){
    for(const c of candidates){
      if(picked.length>=count) break;
      if(!picked.includes(c)) picked.push(c);
    }
  }
  return picked.slice(0,count).map(o=>o.hex);
}
function processPhotoDataUrl(dataUrl){
  const img=new Image();
  img.onload=()=>{
    // сэмплим на разумном разрешении, но масштабируем родным (билинейным)
    // фильтром браузера, не nearest-neighbor. nearest-neighbor вроде звучит
    // заманчиво — держит цвета "чистыми", но на деле просто берёт один
    // случайный исходный пиксель на выходной — а на JPEG этот случайный
    // пиксель с той же вероятностью окажется артефактом сжатия, что и сглаженное
    // билинейным усреднением значение. билинейный + гистограмма/веса выше —
    // вот это сочетание реально устойчивое
    const maxDim=220;
    const scale=Math.min(1,maxDim/Math.max(img.width,img.height));
    const w=Math.max(1,Math.round(img.width*scale)),h=Math.max(1,Math.round(img.height*scale));
    const cv=document.createElement("canvas");cv.width=w;cv.height=h;
    const ctx=cv.getContext("2d",{willReadFrequently:true});
    ctx.drawImage(img,0,0,w,h);
    let data;
    try{data=ctx.getImageData(0,0,w,h).data}catch(e){photoColors=[];photoSelected=[];renderPhotoResults();return}
    const pixels=new Uint8ClampedArray((data.length/4)*3);
    let pi=0;
    for(let i=0;i<data.length;i+=4){
      if(data[i+3]<125) continue; // пропускаем почти прозрачные пиксели
      pixels[pi++]=data[i];pixels[pi++]=data[i+1];pixels[pi++]=data[i+2];
    }
    photoColors=extractPaletteFromPixels(pixels.subarray(0,pi),Math.min(MAX_COLORS,Math.max(5,colors.length)));
    photoSelected=photoColors.slice(0,Math.max(1,colors.length));
    renderPhotoResults();
    if(photoColors.length) showToast(t("toastImageParsed"));
  };
  img.onerror=()=>{photoColors=[];photoSelected=[];renderPhotoResults()};
  img.src=dataUrl;
}
