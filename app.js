// ищет цвета в тексте: #RGB, #RGBA, #RRGGBB, #RRGGBBAA, rgb()/hsl(),
// палитры через дефис как в URL (ff6b5e-1fc2b8-...) и голые 6-значные значения,
// похожие на цвет (есть и цифры, и буквы, или ≤2 разных символов) — так
// обычные слова вроде "decade" или "facade" не попадают в выборку.
// сканирование без lookbehind — в старом Safari такие регулярки не парсятся
function extractHexColors(text){
  text=String(text||"");
  const hits=[];
  const isAlnum=ch=>/[0-9a-zA-Z]/.test(ch);
  const isHex6At=pos=>pos>=0&&/^[0-9a-fA-F]{6}$/.test(text.substr(pos,6))&&!isAlnum(text.charAt(pos-1))&&!isAlnum(text.charAt(pos+6));
  let m;
  const reHash=/#([0-9a-zA-Z]+)/g;
  while((m=reHash.exec(text))){
    const v=m[1];
    if(!/^[0-9a-fA-F]+$/.test(v)) continue;
    if(v.length===3||v.length===4) hits.push({pos:m.index,hex:"#"+v.slice(0,3).split("").map(ch=>ch+ch).join("").toUpperCase()});
    else if(v.length===6||v.length===8) hits.push({pos:m.index,hex:"#"+v.slice(0,6).toUpperCase()});
  }
  const reFn=/\b(rgb|hsl)a?\(([^)]*)\)/gi;
  while((m=reFn.exec(text))){
    const parts=m[2].split(/[\s,\/]+/).filter(Boolean).slice(0,3);
    if(parts.length<3) continue;
    const nums=parts.map(x=>parseFloat(x));
    if(nums.some(n=>!isFinite(n))) continue;
    let h;
    if(m[1].toLowerCase()==="rgb") h=hex(parts.map((x,i)=>Math.max(0,Math.min(255,/%\s*$/.test(x)?nums[i]*2.55:nums[i]))));
    else h=hslToHex(nums[0],nums[1]/100,nums[2]/100);
    hits.push({pos:m.index,hex:h.toUpperCase()});
  }
  const reTok=/[0-9a-zA-Z]+/g;
  while((m=reTok.exec(text))){
    const v=m[0];
    if(v.length!==6||!/^[0-9a-fA-F]{6}$/.test(v)) continue;
    const before=text.charAt(m.index-1),after=text.charAt(m.index+6);
    if(before==="#") continue;
    const inRun=(after==="-"&&isHex6At(m.index+7))||(before==="-"&&isHex6At(m.index-7));
    const looksLikeColor=(/[0-9]/.test(v)&&/[a-fA-F]/.test(v))||new Set(v.toLowerCase()).size<=2;
    if(inRun||looksLikeColor) hits.push({pos:m.index,hex:"#"+v.toUpperCase()});
  }
  hits.sort((a,b)=>a.pos-b.pos);
  const found=[],seen=new Set();
  hits.forEach(h=>{if(!seen.has(h.hex)){seen.add(h.hex);found.push(h.hex)}});
  return found;
}
