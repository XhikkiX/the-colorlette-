// «Fix» (идея 6): двигаем в ПАЛИТРЕ тот из двух цветов, который в ней реально есть и не закреплён.
// производные цвета (onPrimary, muted…) в палитре не лежат — их не трогаем, они пересчитаются сами
function pvFix(pair){
  const [f,b]=pair.split("/"),tk=pvLast.tk;
  for(const [mv,fx] of [[tk[f],tk[b]],[tk[b],tk[f]]]){
    const i=colors.indexOf(mv);
    if(i<0||locked[i])continue;
    const r=fixContrastPair(mv,fx,4.5);
    if(r&&r.bg===fx&&r.fg!==mv){
      pushUndo();colors[i]=r.fg;render(false);scheduleHistoryPush();
      showToast(t("toastContrastFixed")+contrastRatio(r.fg,fx).toFixed(2)+":1",1800);
      return;
    }
  }
  showToast(t("toastContrastImpossible"));
}

