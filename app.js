// обходим все [data-pair], считаем ratio, проставляем data-cr/data-lv (их рисует CSS ::after)
function pvCheck(tk){
  const seen=new Map();
  $("pvFrame").querySelectorAll("[data-pair]").forEach(el=>{
    const [f,b]=el.dataset.pair.split("/"),r=contrastRatio(tk[f],tk[b]),need=el.hasAttribute("data-large")?3:4.5;
    el.dataset.cr=r.toFixed(1);
    el.dataset.lv=r>=7?"aaa":r>=need?"aa":"fail";
    if(r<need){
      const k=f+"/"+b;
      if(!seen.has(k))seen.set(k,{f,b,r,need});
    }
  });
  return [...seen.values()];
}
