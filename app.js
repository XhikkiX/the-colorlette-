// самодельный zip без сжатия, только чтобы упаковать Procreate-шные swatches.json
const CRC_TABLE=(()=>{const table=new Uint32Array(256);for(let n=0;n<256;n++){let c=n;for(let k=0;k<8;k++)c=(c&1)?(0xEDB88320^(c>>>1)):(c>>>1);table[n]=c>>>0}return table})();
function crc32(bytes){let c=0xFFFFFFFF;for(let i=0;i<bytes.length;i++)c=CRC_TABLE[(c^bytes[i])&0xFF]^(c>>>8);return(c^0xFFFFFFFF)>>>0}
function buildZip(files){
  const localParts=[],centralParts=[];let offset=0;
  files.forEach(f=>{
    const nameBytes=strBytes(f.name),crc=crc32(f.data),size=f.data.length;
    const local=concatBytes([u32le(0x04034b50),u16le(20),u16le(0),u16le(0),u16le(0),u16le(0),u32le(crc),u32le(size),u32le(size),u16le(nameBytes.length),u16le(0),nameBytes,f.data]);
    localParts.push(local);
    centralParts.push(concatBytes([u32le(0x02014b50),u16le(20),u16le(20),u16le(0),u16le(0),u16le(0),u16le(0),u32le(crc),u32le(size),u32le(size),u16le(nameBytes.length),u16le(0),u16le(0),u16le(0),u16le(0),u32le(0),u32le(offset),nameBytes]));
    offset+=local.length;
  });
  const centralStart=offset,centralBytes=concatBytes(centralParts);
  const eocd=concatBytes([u32le(0x06054b50),u16le(0),u16le(0),u16le(files.length),u16le(files.length),u32le(centralBytes.length),u32le(centralStart),u16le(0)]);
  return concatBytes([...localParts,centralBytes,eocd]);
}

// Procreate .swatches — ZIP с Swatches.json внутри. схема как у настоящей
// палитры, экспортированной из Procreate 5 (colorSpace/colorModel 0 = sRGB,
// значения HSB рядом с RGB)
function rgbToHsb(r,g,b){
  const max=Math.max(r,g,b),min=Math.min(r,g,b),d=max-min;
  let h=0;
  if(d!==0){
    if(max===r)h=((g-b)/d)%6;else if(max===g)h=(b-r)/d+2;else h=(r-g)/d+4;
    h=(h*60+360)%360/360;
  }
  const s=max===0?0:d/max;
  return[h,s,max];
}
