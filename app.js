function pvShuffle(){
  const n=colors.length;
  if(n<3){showToast(t("pvNeedColors"));return}
  const idx=[...Array(n).keys()];let best=null,bestScore=-1;
  for(let k=0;k<300;k++){
    for(let i=n-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[idx[i],idx[j]]=[idx[j],idx[i]]}
    const a={bg:idx[0],text:idx[1],primary:idx[2]};
    if(n>=4)a.accent=idx[3];
    if(n>=5)a.surface=idx[4];
    const bgC=colors[a.bg],txC=colors[a.text];
    // оценка = худшая из пар: текст/фон, текст/поверхность, primary/фон (для primary достаточно 3:1)
    const s=Math.min(contrastRatio(txC,bgC),a.surface!=null?contrastRatio(txC,colors[a.surface]):99,contrastRatio(colors[a.primary],bgC)*1.5);
    if(s>bestScore){bestScore=s;best={...a}}
    if(s>=4.5)break;
  }
  Object.keys(pv.ov).forEach(k=>{if(k.startsWith(pv.theme+"."))delete pv.ov[k]});
  Object.entries(best).forEach(([tok,i])=>{pv.ov[pv.theme+"."+tok]=i});
  pvRender();syncUrl();showToast(t("pvToastShuffled"));
}
