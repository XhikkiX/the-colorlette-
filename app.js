function ladder(arr,n,i){
  if(n<=1) return arr[Math.floor((arr.length-1)/2)];
  // маленькие палитры не доходят до самых краёв лесенки — иначе 2-3 цвета превращаются в черно-белую пару
  const span=n>=5?[0,1]:n===4?[.04,.96]:n===3?[.10,.90]:[.20,.80];
  const t=span[0]+(span[1]-span[0])*i/(n-1);
  const pos=t*(arr.length-1),lo=Math.floor(pos),hi=Math.min(arr.length-1,lo+1),f=pos-lo;
  return arr[lo]*(1-f)+arr[hi]*f;
}
