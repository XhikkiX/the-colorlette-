function getCurrentPaletteName(){
  // источник правды для имени палитры — история. ищем самую свежую запись
  // с ровно теми же цветами, что сейчас на экране — так переименование
  // отражается в PNG без второго поля имени, которое могло бы разъехаться
  const current=colors.map(c=>valid(c)).join(',');
  const match=history.find(h=>Array.isArray(h.colors)&&h.colors.map(c=>valid(c)).join(',')===current);
  return String(match?.name||'').trim();
}
// единая точка входа для "как называется текущая палитра при экспорте".
// getCurrentPaletteName() смотрит в историю — но если палитру ещё не
// сохранили (например, юзер жмёт "Экспорт" быстрее, чем сработает
// orderHistTimer), там будет пусто. на этот случай — свежая генерация
// имени по тем же цветам, чтобы имя не было пустым никогда
function paletteNameForExport(){
  return getCurrentPaletteName()||autoNameFor(colors);
}
// generatePaletteName() каждый раз бросает кубик — без кэша имя в превью PNG
// прыгало бы при каждой перерисовке и отличалось бы от того, что попадёт
// в ASE/GPL/JSON. кэш держит одно имя на связку «язык + цвета»,
// а addHistory() потом кладёт в историю именно его
let autoName={key:"",lang:"",seed:null,name:""};
function autoNameFor(cols){
  const key=cols.map(c=>valid(c)).join(",");
  if(autoName.key!==key)autoName={key,lang,seed:newNameSeed(),name:""};
  if(autoName.lang!==lang||!autoName.name){autoName.lang=lang;autoName.name=generatePaletteName(cols,autoName.seed)}
  return autoName.name;
}
function fitCanvasText(ctx,text,maxWidth,maxFontSize,minFontSize=28){
  let size=maxFontSize;
  while(size>minFontSize){
    ctx.font=`800 ${size}px Arial, sans-serif`;
    if(ctx.measureText(text).width<=maxWidth)return size;
    size-=2;
  }
  ctx.font=`800 ${minFontSize}px Arial, sans-serif`;
  return minFontSize;
}


