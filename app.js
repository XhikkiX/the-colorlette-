// минимальный сдвиг светлоты (в OKLCH, оттенок/chroma не трогаем), чтобы
// дотянуть пару до цели WCAG. сначала двигаем текст, фон трогаем только
// если одним текстом не дотянуться
// Я заебался очень напишите кто нибудь за меня это пж
function fixContrastPair(fg,bg,target){
  const shift=(moving,fixed)=>{
    const [L0,C,H]=rgbToOklch(moving);
    const dirs=luminance(moving)>=luminance(fixed)?[1,-1]:[-1,1];
    for(const dir of dirs){
      const end=dir>0?1:0;
      if(contrastRatio(oklchToHex(end,C,H),fixed)<target) continue;
      let lo=L0,hi=end;
      for(let i=0;i<24;i++){const mid=(lo+hi)/2;if(contrastRatio(oklchToHex(mid,C,H),fixed)>=target)hi=mid;else lo=mid}
      return oklchToHex(hi,C,H);
    }
    return null;
  };
  const nf=shift(fg,bg);if(nf) return {fg:nf,bg};
  const nb=shift(bg,fg);if(nb) return {fg,bg:nb};
  return null;
}
