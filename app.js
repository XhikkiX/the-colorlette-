// --- Sort menu: order the current palette by lightness / hue / saturation / temperature --------
// у каждого режима есть "основное" направление (свет→тьма, по кругу, ярко→тускло,
// тепло→холодно); повторный выбор того же режима переворачивает его
function sortOrder(p,crit){
  const key=p.map(c=>{
    const [L,C,H0]=rgbToOklch(c),H=(H0+360)%360;
    if(crit==="hue") return C<.02?1000-L:H;                         // greys go last, light → dark
    if(crit==="sat") return -C;
    if(crit==="temp") return -Math.cos((H-50)*Math.PI/180)*(.35+.65*Math.min(1,C/.12)); // warmth peaks near orange
    return -L;                                                        // light → dark
  });
  return p.map((_,i)=>i).sort((x,y)=>key[x]-key[y]||x-y);
}
