// генерим кучу кандидатов, оцениваем на "приятность глазу", берём случайный
// из лучших — так есть и минимальная планка качества, и реальное разнообразие
// на каждый клик, а не один и тот же топ-вариант каждый раз
//
// base/fillIndices дают вмонтировать кандидата в уже существующую палитру
// перед оценкой: fillIndices — какие слоты реально меняются, остальное берётся
// из base как есть. Из-за этого закреплённые цвета (или остальные 4, когда
// перегенерим один) реально участвуют в оценке — кандидат, который не сочетается
// с закреплённым цветом, теперь проигрывает, а не судится в вакууме
