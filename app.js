function hexToRgb01(hex){const v=hex.replace("#","");return[parseInt(v.slice(0,2),16)/255,parseInt(v.slice(2,4),16)/255,parseInt(v.slice(4,6),16)/255]}
function u16le(v){return new Uint8Array([v&0xFF,(v>>>8)&0xFF])}
function u32le(v){return new Uint8Array([v&0xFF,(v>>>8)&0xFF,(v>>>16)&0xFF,(v>>>24)&0xFF])}
function u16be(v){return new Uint8Array([(v>>>8)&0xFF,v&0xFF])}
function u32be(v){return new Uint8Array([(v>>>24)&0xFF,(v>>>16)&0xFF,(v>>>8)&0xFF,v&0xFF])}
function f32be(v){const b=new Uint8Array(4);new DataView(b.buffer).setFloat32(0,v,false);return b}
function concatBytes(arrs){let len=0;arrs.forEach(a=>len+=a.length);const out=new Uint8Array(len);let o=0;arrs.forEach(a=>{out.set(a,o);o+=a.length});return out}
function strBytes(s){return new TextEncoder().encode(s)}
function exportNames(){const roles=getDisplayRoles();return colors.map((c,i)=>roleLabel(roles[i]))}
// Сохранение файла. В Telegram Mini App обычный <a download> с blob-ссылкой не работает,
// поэтому файл временно кладётся на воркер, а Telegram скачивает его по ссылке.
async function saveBlob(blob,filename){
  const tg=window.Telegram&&window.Telegram.WebApp;
  const api=(window.COLORLETTE_PRO_API||"").replace(/\/$/,"");
  if(tg&&tg.initData&&api){
    try{
      const r=await fetch(api+"/file/upload?name="+encodeURIComponent(filename)+"&type="+encodeURIComponent(blob.type||"application/octet-stream"),{
        method:"POST",
        headers:{"X-Telegram-Init-Data":tg.initData,"Content-Type":"application/octet-stream"},
        body:blob,
        credentials:"omit"
      });
      const j=await r.json();
      if(!r.ok||!j.url)throw new Error(j.error||("HTTP "+r.status));
      if(typeof tg.downloadFile==="function"&&(!tg.isVersionAtLeast||tg.isVersionAtLeast("8.0"))){
        tg.downloadFile({url:j.url,file_name:filename});
      }else if(tg.openLink){
        tg.openLink(j.url);
      }else{
        window.open(j.url,"_blank");
      }
      return true;
    }catch(e){/* если не вышло — пробуем обычное скачивание ниже */}
  }
  const url=URL.createObjectURL(blob);
  const a=document.createElement("a");
  a.href=url;a.download=filename;a.rel="noopener";
  a.style.position="fixed";a.style.left="-9999px";
  document.body.appendChild(a);a.click();a.remove();
  setTimeout(()=>URL.revokeObjectURL(url),1000);
  return false;
}
function downloadBytes(bytes,filename,mime){
  saveBlob(new Blob([bytes],{type:mime}),filename);
}

// Adobe Swatch Exchange (.ase) — бинарник, big-endian. открывается прямо в
// Photoshop, Illustrator, InDesign, Affinity
function aseNameBlock(name){
  const s=name+"\u0000";
  const nameBytes=new Uint8Array(s.length*2);
  for(let c=0;c<s.length;c++){nameBytes[c*2]=(s.charCodeAt(c)>>>8)&0xFF;nameBytes[c*2+1]=s.charCodeAt(c)&0xFF}
  return{s,nameBytes};
}
function aseGroupStart(name){
  const{s,nameBytes}=aseNameBlock(name);
  const data=concatBytes([u16be(s.length),nameBytes]);
  return concatBytes([u16be(0xC001),u32be(data.length),data]); // 0xC001 = group start
}
function aseGroupEnd(){
  return concatBytes([u16be(0xC002),u32be(0)]); // 0xC002 = group end, no data
}
// Пупупу
function buildASE(hexColors,names,groupName){
  const blocks=hexColors.map((hex,i)=>{
    const{s,nameBytes}=aseNameBlock(names[i]||`Color ${i+1}`);
    const[r,g,b]=hexToRgb01(hex);
    const data=concatBytes([u16be(s.length),nameBytes,strBytes("RGB "),f32be(r),f32be(g),f32be(b),u16be(0)]);
    return concatBytes([u16be(0x0001),u32be(data.length),data]);
  });
  const wrapped=groupName?[aseGroupStart(groupName),...blocks,aseGroupEnd()]:blocks;
  const header=concatBytes([strBytes("ASEF"),u16be(1),u16be(0),u32be(wrapped.length)]);
  return concatBytes([header,...wrapped]);
}
