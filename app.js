// рост: каждый новый цвет вставляется туда, где соседи дальше всего друг
// от друга (заполняет реальную дыру), и генерится с учётом всей палитры
// Чето тут не так ну похуй потом разберёмся
function growPalette(n){
  const cols=[...colors],lk=[...locked];let fresh=[];
  const anchor=vividHue(colors);
  while(cols.length<n){
    let at=cols.length,bestD=-1;
    for(let i=0;i<cols.length-1;i++){const d=hexDistance(cols[i],cols[i+1]);if(d>bestD){bestD=d;at=i+1}}
    const tmp=cols.length>1&&at<cols.length?mix(cols[at-1],cols[at],.5):mix(cols[cols.length-1],"#FFFFFF",.4);
    cols.splice(at,0,tmp);lk.splice(at,0,false);
    fresh=fresh.map(i=>i>=at?i+1:i);fresh.push(at);
  }
  const gen=generateHarmony(anchor,cols,fresh);
  // новые цвета наследуют характер палитры: насыщенность от уже существующих
  // цветов, светлота подтягивается к соседям. без этого у яркой палитры
  // новые цвета выходили грязно-оливковыми/почти-чёрными прямо с лесенки настроения
  const avgS=colors.reduce((a,c)=>a+hexToHsl(c)[1],0)/colors.length;
  fresh.forEach(i=>{
    const [h,s,l]=hexToHsl(gen[i]);
    const nb=[gen[i-1],gen[i+1]].filter(Boolean).map(c=>hexToHsl(c)[2]);
    const nl=nb.length?nb.reduce((a,b)=>a+b,0)/nb.length:l;
    gen[i]=hslToHex(h,clamp01(s*.35+avgS*.65),clamp01(l*.5+nl*.5));
  });
  colors=gen;locked=lk;
}
// сжатие: убираем незакреплённый цвет, без которого палитра оценивается лучше всего
// ХАХАПХПХПХААЭ
function shrinkPalette(n){
  const cols=[...colors],lk=[...locked];
  while(cols.length>n){
    const free=cols.map((_,i)=>i).filter(i=>!lk[i]);
    let drop=cols.length-1;
    if(free.length){
      let bestS=-Infinity;
      free.forEach(i=>{const sc=scorePalette(cols.filter((_,j)=>j!==i));if(sc>bestS){bestS=sc;drop=i}});
    }
    cols.splice(drop,1);lk.splice(drop,1);
  }
  colors=cols;locked=lk;
}
