function bestOfPool(shapes,baseHue,hueJitter,useBias,base=null,fillIndices=null){
  const pool=[];
  for(let i=0;i<40;i++){
    const shape=fitShape(shapes[Math.floor(Math.random()*shapes.length)],paletteSize(base));
    const cand=buildCandidate(shape,baseHue,hueJitter,useBias);
    const merged=base?base.map((c,idx)=>fillIndices.includes(idx)?cand[idx]:c):cand;
    pool.push({c:merged,score:scorePalette(merged)});
  }
  pool.sort((a,b)=>b.score-a.score);
  const shortlist=pool.slice(0,Math.max(10,Math.round(pool.length*.35)));
  return shortlist[Math.floor(Math.random()*shortlist.length)].c;
}
