// ближайший контейнер, который РЕАЛЬНО скроллится по горизонтали (полоса вкладок). overflow:hidden-предков
// (например .panel) не трогаем — иначе scrollIntoView сдвигал их «намертво» вправо/влево.
function findHScroller(el){
  for(let p=el.parentElement;p&&p!==document.body&&p!==document.documentElement;p=p.parentElement){
    const o=getComputedStyle(p).overflowX;
    if((o==="auto"||o==="scroll")&&p.scrollWidth>p.clientWidth+1) return p;
  }
  return null;
}
function scrollToTarget(el){
  const sc=findHScroller(el);
  let r=el.getBoundingClientRect();
  if(sc){
    const sr=sc.getBoundingClientRect();
    const left=sc.scrollLeft+(r.left-sr.left)-(sr.width-r.width)/2;
    sc.scrollTo({left:Math.max(0,left),behavior:"smooth"});
  }
  const top=window.scrollY+r.top+r.height/2-tourVH()/2;
  window.scrollTo({top:Math.max(0,top),behavior:"smooth"});
}
// ждём, пока сама цель перестанет двигаться (вертикальный скролл, полоса вкладок, анимация появления вкладки)
function waitForScrollSettle(cb,el,token){
  let lastT=null,lastL=null,stable=0,frames=0;
  function tick(){
    if(token!==tourToken) return;
    frames++;
    const r=el.getBoundingClientRect();
    if(lastT!==null&&Math.abs(r.top-lastT)<0.5&&Math.abs(r.left-lastL)<0.5) stable++; else stable=0;
    lastT=r.top;lastL=r.left;
    if(stable>=5||frames>=100){cb();return}
    requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
}
